def classify(name):
    for cls, kws in INDUSTRY_CLASS:
        if any(k in name for k in kws):
            return cls
    return '其他'

def fetch_momentum_rank():
    # 有当天缓存则复用（重建时全市场数据当天不变，省 6 分钟）
    import datetime
    today = datetime.date.today().isoformat()
    if os.path.exists(CACHE):
        try:
            cache = json.load(open(CACHE, encoding='utf-8'))
            if cache.get('date') == today and cache.get('pool'):
                print(f'  使用缓存（{today}，{len(cache["pool"])} 只）')
                return cache['pool']
        except Exception:
            pass
    out = {}
    for off in range(0, 1640, 20):
        r = subprocess.run([NODE, CLI, 'ranking', 'qt_chg_interval', '--asset', 'etf',
                            '--offset', str(off), '--limit', '20'],
                           capture_output=True, text=True, encoding='utf-8', timeout=90)
        if r.returncode != 0:
            continue
        for line in r.stdout.splitlines():
            line = line.strip()
            if not (line.startswith('| sh') or line.startswith('| sz')):
                continue
            parts = [p.strip() for p in line.split('|')]
            parts = [p for p in parts if p]
            if len(parts) < 8:
                continue
            code = parts[0]
            if not re.match(r'^(sh|sz)\d{6}$', code):
                continue
            try:
                out[code] = {
                    'name': parts[1],
                    'chg1d': float(parts[2]), 'chg20d': float(parts[3]),
                    'chg52w': float(parts[4]), 'chg5d': float(parts[5]),
                    'chg60d': float(parts[6]), 'chgytd': float(parts[7]),
                }
            except (ValueError, IndexError):
                continue
        if off % 400 == 0:
            print(f'  已拉取 {len(out)} 只', flush=True)
    # 写缓存
    with open(CACHE, 'w', encoding='utf-8') as f:
        json.dump({'date': today, 'pool': out}, f, ensure_ascii=False)
    return out

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--per_industry', type=int, default=6, help='每行业保留代表数(默认6)')
    parser.add_argument('--max_total', type=int, default=110, help='池子上限(默认110)')
    args = parser.parse_args()

    print('== 1/4 拉取全市场动量榜 ==')
    pool = fetch_momentum_rank()
    print(f'全市场: {len(pool)} 只')

    print('== 2/4 筛选行业/主题型 ==')
    selected = {c: v for c, v in pool.items() if is_industry(v['name'])}
    print(f'行业/主题型: {len(selected)} 只')

    print('== 3/4 行业分层 + 向上趋势优先排序 ==')
    for c, v in selected.items():
        # 评分：向上趋势大幅加分，兼顾波动活跃度
        # 三层：双多(20&60日为正) >> 单多(20日为正) >> 弱势(20日为负)
        if v['chg20d'] > 0 and v['chg60d'] > 0:
            base = abs(v['chg20d']) + abs(v['chg60d']) + 50   # 双多：趋势向上，优先
        elif v['chg20d'] > 0:
            base = abs(v['chg20d']) + abs(v['chg60d']) + 25   # 单多：初步修复
        else:
            base = abs(v['chg20d']) * 0.6 + abs(v['chg60d']) * 0.4  # 弱势：保留波动但排后
        # 5日动量为正再加分（近期动能）
        if v['chg5d'] > 0:
            base += 10
        v['active_score'] = round(base, 2)
        v['industry'] = classify(v['name'])
        if v['chg20d'] > 0 and v['chg5d'] > 0:
            v['signal'] = '申购/持有'
        elif v['chg20d'] > 0:
            v['signal'] = '观察'
        else:
            v['signal'] = '赎回/规避'

    # 按行业分组，组内按 active_score 降序取前 per_industry
    from collections import defaultdict
    groups = defaultdict(list)
    for c, v in selected.items():
        groups[v['industry']].append((c, v))
    chosen = {}
    for cls, items in sorted(groups.items(), key=lambda x: -len(x[1])):
        items.sort(key=lambda x: -x[1]['active_score'])
        for c, v in items[:args.per_industry]:
            chosen[c] = v
    # 若超上限，砍掉 active_score 最低的
    if len(chosen) > args.max_total:
        chosen = dict(sorted(chosen.items(), key=lambda x: -x[1]['active_score'])[:args.max_total])
    print(f'池大小: {len(chosen)} 只 | 覆盖行业: {len(groups)} 个')

    # 落盘到 lib/（run.py 的 LIB_DIR 依赖查找路径）
    targets = [
        os.path.join(LIB, 'top100_etf.json'),
    ]
    for t in targets:
        os.makedirs(os.path.dirname(t), exist_ok=True)
        with open(t, 'w', encoding='utf-8') as f:
            json.dump(chosen, f, ensure_ascii=False, indent=1)
        print(f'  已写入: {t}')

    # 概览：行业分布 + 每行业代表
    from collections import Counter
    cls_cnt = Counter(v['industry'] for v in chosen.values())
    print('\n行业分布:')
    for cls, cnt in cls_cnt.most_common():
        print(f'  {cls}: {cnt} 只')
    print('\n每行业代表(前2):')
    seen = set()
    for c, v in sorted(chosen.items(), key=lambda x: -x[1]['active_score']):
        if v['industry'] in seen:
            continue
        seen.add(v['industry'])
        print(f"  [{v['industry']}] {c} {v['name']} act:{v['active_score']} 20D:{v['chg20d']:+.1f}%")

