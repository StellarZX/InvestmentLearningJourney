# 快速行业关键词（用于 is_industry 判断是否行业/主题型）
INDUSTRY_KW_QUICK = [k for _, kws in INDUSTRY_CLASS for k in kws]


def is_industry(name):
    """是否为行业/主题型 ETF（排除宽基/跨境/债券/商品/货币）"""
    if any(k in name for k in EXCLUDE_KW):
        return False
    return any(k in name for k in INDUSTRY_KW_QUICK)


def macd_series(close):
    """计算 MACD 的 DIF/DEA 序列（EWM 12/26/9）"""
    ema_f = close.ewm(span=12, adjust=False).mean()
    ema_s = close.ewm(span=26, adjust=False).mean()
    dif = ema_f - ema_s
    dea = dif.ewm(span=9, adjust=False).mean()
    return dif, dea
