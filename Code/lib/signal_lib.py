def theme_of(name):
    """识别 ETF 的细分主题（去基金公司、去尾缀、同义词归一），同主题视为同一细分方向。
    例: 黄金股ETF永赢/华夏/工银 -> 黄金股ETF（同一细分方向）"""
    t = name
    for c in sorted(FUND_COMPANIES, key=len, reverse=True):
        if t.endswith(c):
            t = t[: -len(c)]
            break
    # 清理尾缀
    for suf in ['ETF联接', '联接', 'LOF', '-C', '-A', 'C', 'A']:
        if t.endswith(suf):
            t = t[: -len(suf)]
            break
    # 同义词归一（同一细分方向的不同名称写法）
    for alias, canon in [('有色金属', '有色'), ('工业有色', '有色'), ('新能源电池', '电池'),
                         ('港股通科技', '恒生科技'), ('中概互联网', '中概互联')]:
        if alias in t:
            t = t.replace(alias, canon)
    t = t.strip()
    return t if t else name


